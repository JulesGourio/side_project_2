"""code_normalization.py — one spelling for the codes of the passages and of the search queries.

A code is written several ways in the documents and in the questions (``SF-1027``, ``SF 1027``, ``sf-1027``,
``SF‑1027_BG``, ``MI - 1365``). The keyword side of the hybrid search only matches the same spelling, so each code
found keeps its spelling and gets its canonical form appended in brackets, after the word that holds it:
``SF-1027`` -> ``SF-1027 [SF1027]``, ``MI-13991Table`` -> ``MI-13991Table [MI13991]``.

Three kinds of codes are found, by three matchers whose results are merged (the earliest, then the longest wins):

- **catalog REFs**, every format (``Q0697MI_FR``, ``LdB IT-243``, ``777F-MDCD-QP``, ``19 --058``): the text is cut
  into pieces of letters or digits, neighbouring pieces are glued, and the longest run whose key is a key of the
  catalog (``CATALOG_CANONICAL``) is kept;
- **REFs absent from the catalog** (obsolete, other site, typing error: ``SF-1027``, ``NS-1717``, ``Q0256MI``): the
  regex of a REF family (``CODE_FAMILIES``, site codes, lettres de branchement, programme phases) finds the shape,
  and the code is kept when one of its cuts is a catalog key, or has the signature of a catalog REF
  (``REF_SIGNATURES``: ``SF9999`` for ``SF-1029``);
- **codes that are not REFs** (standards, aircraft, regulations, alloys, ATA chapters, SAP transactions, part
  numbers, acronyms written letter by letter): the hand-written ``EXTRA_PATTERNS``.

The canonical form of a catalog key is its REF upper-cased, without separators and without language suffix
(``SF-1027_BG`` -> ``SF1027``, ``doc_catalog._canon``); a key that several REFs share (``777F``, ``QIS45D008`` with
revisions A and B) is its own canonical form; a key that one REF completes (``QIS46A352`` for ``QIS-46A-352 A``) takes
that REF. Diacritics are dropped (``ŘLCZ-07/18`` -> ``RLCZ0718``).

``cited_codes`` lists the codes a passage cites (column ``cited_codes``), from which the parsing pipeline builds the
table of the documents that cite each code (``doc_references``, read by the chat for "which documents cite X?").

The same rules must run on both sides, or the brackets never meet: the parsing pipeline writes the passages'
``chunk_preprocessed`` column with ``normalize_codes`` (this module is shipped to the executors, see
``config.WORKER_MODULES``), and the app rewrites the search queries with ``normalize_query`` (imported as
``utils.parsing_pipeline.code_normalization``). Standard library only, for that reason, and the catalog data is a
generated block of this file.

The generated blocks (``CODE_FAMILIES`` and the catalog) come from the REFs of the document catalog:
``python code_normalization.py <file with one REF per line>`` rewrites them in this file. Changing a generated block,
the hand-written patterns or the matching changes the passages: bump ``NORMALIZATION_VERSION``, rebuild the chunk
tables (``run_mode=rechunk``) and sync the indexes again.
"""

