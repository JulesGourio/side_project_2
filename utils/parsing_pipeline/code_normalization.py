"""code_normalization.py — one spelling for the reference codes of the passages and of the search queries.

A code is written several ways in the documents and in the questions (``SF-1027``, ``SF1027``, ``SF 1027``,
``SF_1027``). The keyword side of the hybrid search only matches the same spelling, so each code found keeps its
spelling and gets its canonical form appended in brackets: ``SF-1027`` -> ``SF-1027 [SF1027]``. The canonical form is
the code upper-cased, without separators and without language suffix (``SF-1027_BG`` -> ``SF1027``), the same key as
``doc_catalog._canon``.

``cited_codes`` lists the codes a passage cites (column ``cited_codes``), from which the parsing pipeline builds the
table of the documents that cite each code (``doc_references``, read by the chat for "which documents cite X?").

The same rules must run on both sides, or the brackets never meet: the parsing pipeline writes the passages'
``chunk_preprocessed`` column with ``normalize_codes`` (this module is shipped to the executors, see
``config.WORKER_MODULES``), and the app rewrites the search queries with ``normalize_query``
(imported as ``utils.parsing_pipeline.code_normalization``). Standard library only, for that reason.

The code families come from the REFs of the document catalog (``CODE_FAMILIES``, generated by ``families_from_refs``:
``python code_normalization.py <file with one REF per line>`` writes the block to paste). Codes that are not REFs of
the catalog (external standards...) go in ``EXTRA_PATTERNS``, by hand. Changing either list changes the passages: the
chunk tables must be rebuilt (``run_mode=rechunk``) and the indexes synced again.
"""

import re
import sys
from functools import lru_cache
from typing import Dict, Iterable, List, NamedTuple, Pattern, Tuple


class CodeFamily(NamedTuple):
    """Shape of the codes of one prefix, as the catalog REFs write them.

    ``min_digits``/``max_digits``: digits of the first number group; ``groups``: most number groups after the prefix
    (``DLV-33-3010`` has 2); ``spaced``: a space may separate two number groups (``IAQ 10 01 01``).
    """

    min_digits: int
    max_digits: int
    groups: int
    spaced: bool


