# --- Hand-written patterns ---
# Codes that are not catalog REFs (external standards...): one regex per entry, the whole match is the code. Example:
# r"\bEN[-_ ]?9100\b". Flags go inside the pattern ((?i) for a case-insensitive match).
EXTRA_PATTERNS: List[str] = []

# Prefixes never treated as codes, even when a catalog REF uses them: words and language codes that a number follows
# in ordinary text ("GB 128", "in 300").
STOP_PREFIXES = frozenset({"GB", "IN", "EN", "FR", "ES", "IS", "OF", "ON", "NO", "AT", "TO", "DE", "LE", "LA", "ET"})

# Catalog REFs end with a language, site or variant suffix (SF-1027_BG, QM-1064-IS, QIS-46L-154 D): not part of the code.
_REF_SUFFIX_RE = re.compile(r"(?:[-_. ]+[A-Z]+)+$")
_REF_SHAPE_RE = re.compile(r"^([A-Z]{2,6})[-_. ]?(\d+)[A-Z]?((?:[-_./ ]\d+[A-Z]?)*)$")
_NON_ALNUM_RE = re.compile(r"[^0-9A-Za-z]")
# The "[Source: <REF> | Title: ...]" line every passage starts with: it names the passage's own document, not a citation.
_SOURCE_PREFIX_RE = re.compile(r"^\[Source: [^\n]*\]\s*")
# A language suffix stays with the code it ends (SF-1027_BG [SF1027]) but is not part of the canonical form.
_LANGUAGE_SUFFIX = r"(?:[-_](?:[Ff][Rr]|[Ee][Nn]|[Gg][Bb]|[Mm][Xx]|[Bb][Gg]|[Cc][Zz]|[Bb][Rr]|[Ee][Ss]))?"
_MIN_REFS_PER_FAMILY = 2


# --- Matching ---

def canonical(code: str) -> str:
    """Canonical form of a code: upper-cased, letters and digits only.

    :param code: code as written, e.g. ``SF-1027`` or ``sf 1027``
    :return: e.g. ``SF1027``
    """
    return _NON_ALNUM_RE.sub("", code).upper()


@lru_cache(maxsize=4)
def _patterns(families: Tuple[Tuple[str, CodeFamily], ...], extras: Tuple[str, ...],
              accept_lowercase: bool) -> List[Pattern]:
    """Compiled patterns: one per family shape (the prefixes sharing it alternate), then the hand-written ones.

    :param families: ``CODE_FAMILIES`` items, as a tuple so the result is cached
    :param extras: ``EXTRA_PATTERNS``, as a tuple
    :param accept_lowercase: also match a prefix written in lower case (questions: ``sf-1027``)
    :return: the compiled patterns
    """
    by_shape: Dict[CodeFamily, List[str]] = {}
    for prefix, family in families:
        if prefix not in STOP_PREFIXES:
            by_shape.setdefault(family, []).append(prefix)
    patterns = []
    for family, prefixes in by_shape.items():
        spellings = prefixes + [p.lower() for p in prefixes] if accept_lowercase else prefixes
        alternation = "|".join(re.escape(p) for p in sorted(spellings, key=len, reverse=True))
        separator = "[-_./ ]" if family.spaced else "[-_./]"
        more_groups = f"(?:{separator}\\d{{1,6}}[A-Z]?){{0,{family.groups - 1}}}"
        patterns.append(re.compile(
            rf"(?<![A-Za-z0-9])(?P<code>(?:{alternation})[-_. ]?\d{{{family.min_digits},{family.max_digits}}}[A-Z]?"
            rf"{more_groups}){_LANGUAGE_SUFFIX}(?![A-Za-z0-9])"))
    return patterns + [re.compile(p) for p in extras]


def find_codes(text: str, accept_lowercase: bool = False) -> List[Tuple[int, int, str]]:
    """The codes of a text, left to right; of two overlapping matches the one starting first (then the longest) wins.

    :param text: passage or query
    :param accept_lowercase: also match a prefix written in lower case
    :return: ``(start, end, canonical form)`` of each code; the span includes a language suffix (``SF-1027_BG``)
    """
    if not text:
        return []
    spans = []
    for pattern in _patterns(tuple(CODE_FAMILIES.items()), tuple(EXTRA_PATTERNS), accept_lowercase):
        has_code = "code" in pattern.groupindex
        spans += [(m.start(), m.end(), m.group("code") if has_code else m.group(0)) for m in pattern.finditer(text)]
    found, last_end = [], -1
    for start, end, code in sorted(spans, key=lambda s: (s[0], -s[1])):
        if start >= last_end:
            found.append((start, end, canonical(code)))
            last_end = end
    return found


def normalize_codes(text: str, accept_lowercase: bool = False) -> str:
    """The text with ``[canonical]`` after each code written another way: ``SF-1027`` -> ``SF-1027 [SF1027]``.

    A code already in its canonical spelling, or already followed by its bracket, is left as it is (running the
    function twice changes nothing).

    :param text: passage or query
    :param accept_lowercase: also match a prefix written in lower case (questions)
    :return: the text with the canonical forms added; ``text`` itself when it has no code
    """
    out, position = [], 0
    for start, end, canon in find_codes(text, accept_lowercase):
        bracket = f" [{canon}]"
        if text[start:end] == canon or text.startswith(bracket, end):
            continue
        out += [text[position:end], bracket]
        position = end
    return "".join(out) + text[position:] if out else text


def normalize_query(query: str) -> str:
    """``normalize_codes`` for a search query: a question may write the prefix in lower case (``sf-1027``).

    :param query: search text
    :return: the query with the canonical forms added
    """
    return normalize_codes(query, accept_lowercase=True)


def canonical_codes(text: str, accept_lowercase: bool = False) -> List[str]:
    """The distinct canonical codes of a text, in order of first appearance.

    :param text: passage or query
    :param accept_lowercase: also match a prefix written in lower case
    :return: e.g. ``["SF1027", "QP1518"]``
    """
    return list(dict.fromkeys(canon for _, _, canon in find_codes(text, accept_lowercase)))


def cited_codes(chunk_text: str, ref: str) -> List[str]:
    """The codes a passage cites: the canonical codes of its body, without its ``[Source: …]`` line and without the
    codes of its own document (``Q0102QP_GB`` citing ``SF-1027`` -> ``["SF1027"]``).

    :param chunk_text: passage text, with or without its source line
    :param ref: REF of the passage's document
    :return: the distinct canonical codes, in order of first appearance
    """
    own = set(canonical_codes(ref or ""))
    body = _SOURCE_PREFIX_RE.sub("", chunk_text or "", count=1)
    return [code for code in canonical_codes(body) if code not in own]


# --- Generation of CODE_FAMILIES ---

def families_from_refs(refs: Iterable[str], min_refs: int = _MIN_REFS_PER_FAMILY) -> Dict[str, CodeFamily]:
    """Code families of a list of catalog REFs: one per letter prefix followed by numbers (``SF-1027``, ``DLV-33-3010``,
    ``IAQ 10 01 01``). REFs of another shape (``Q0102QP``, ``LdB P-139``) are left out: they are written one way.

    :param refs: REFs, any case, with or without language suffix
    :param min_refs: fewest distinct codes a prefix needs to become a family (fewer is more likely noise)
    :return: the families by prefix, prefixes in alphabetical order
    """
    seen: Dict[str, set] = {}
    stats: Dict[str, List] = {}
    for ref in refs:
        m = _REF_SHAPE_RE.match(_REF_SUFFIX_RE.sub("", (ref or "").strip().upper()))
        if not m:
            continue
        prefix, first, rest = m.groups()
        canon = canonical(m.group(0))
        if canon in seen.setdefault(prefix, set()):
            continue
        seen[prefix].add(canon)
        groups = 1 + len(re.findall(r"[-_./ ]\d", rest))
        spaced = " " in rest
        lo, hi, most, any_spaced = stats.get(prefix, [len(first), len(first), groups, spaced])
        stats[prefix] = [min(lo, len(first)), max(hi, len(first)), max(most, groups), any_spaced or spaced]
    return {prefix: CodeFamily(*stats[prefix]) for prefix in sorted(stats)
            if len(seen[prefix]) >= min_refs and prefix not in STOP_PREFIXES}


def render_families(families: Dict[str, CodeFamily]) -> str:
    """The ``CODE_FAMILIES`` block to paste in this module.

    :param families: result of ``families_from_refs``
    :return: Python source of the dict
    """
    lines = [f"    {prefix!r}: CodeFamily({f.min_digits}, {f.max_digits}, {f.groups}, {f.spaced}),"
             for prefix, f in families.items()]
    return "CODE_FAMILIES: Dict[str, CodeFamily] = {\n" + "\n".join(lines) + "\n}\n"


