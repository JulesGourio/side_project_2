# Version of the rules written into the passages: a passage normalised by another version needs a rechunk.
NORMALIZATION_VERSION = 2


class CodeFamily(NamedTuple):
    """Shape of the codes of one prefix, as the catalog REFs write them.

    ``min_digits``/``max_digits``: digits of the first number group; ``groups``: most number groups after the prefix
    (``DLV-33-3010`` has 2); ``spaced``: a space may separate two number groups (``IAQ 10 01 01``).
    """

    min_digits: int
    max_digits: int
    groups: int
    spaced: bool


class ExtraPattern(NamedTuple):
    """A code family that is not a catalog REF.

    ``regex``: the whole match, or its group ``code``, is the code; ``key``: a regex the canonical form must match
    (empty: any).
    """

    name: str
    regex: str
    key: str = ""


def _parse_keys(block: str) -> Dict[str, str]:
    """Catalog keys of a generated block: ``KEY=CANONICAL`` or ``KEY`` (its own canonical form), separated by spaces.

    :param block: text of ``_CATALOG_KEYS``
    :return: canonical form by key
    """
    return dict((w.split("=", 1) * 2)[:2] if "=" not in w else w.split("=", 1) for w in block.split())


