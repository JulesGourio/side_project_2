class _Match(NamedTuple):
    """A code found by one matcher: span in the text, canonical form, rank of the matcher (0 catalog, 1 REF shape,
    2 hand-written pattern; the lowest wins a tie) and its name (``CATALOG``, ``REF_SHAPE`` or the pattern's name).
    """

